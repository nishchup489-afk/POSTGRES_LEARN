/*
\copy imports a local CSV file through psql.

Main rules:

1. The destination table must already exist.
2. The table name must be correct.
3. The CSV column count must match the \copy column count.
4. The column order must match the CSV order.
5. Use HEADER when the first row contains column names.
6. On Windows, prefer forward slashes in file paths.
7. Enter the entire \copy command on one line.
8. If importing manual identity IDs, synchronize the sequence afterward.
*/


