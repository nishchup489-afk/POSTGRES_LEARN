-- =====================================================================
--                     COMMON ERROR: TYPO
-- =====================================================================

/*
Wrong:

WITH DELIMER ',' CSV

Correct spelling:

DELIMITER

Modern preferred syntax:

WITH (FORMAT CSV, DELIMITER ',', HEADER)

Because comma is already the default CSV delimiter,
this is usually enough:

WITH (FORMAT CSV, HEADER)
*/


-- =====================================================================
--                        WINDOWS FILE PATHS
-- =====================================================================

/*
Prefer forward slashes:

'C:/Users/nishc/Downloads/MOCK_DATA.csv'

This is safer and easier than:

'C:\Users\nishc\Downloads\MOCK_DATA.csv'
*/


-- =====================================================================
--                        HEADER VS NO HEADER
-- =====================================================================

/*
Use HEADER when the first CSV row contains column names.

Example:

id,first_name,last_name,email,gender,ip_address
1,John,Doe,john@example.com,Male,127.0.0.1

Command:

WITH (FORMAT CSV, HEADER)


Do not use HEADER when the file begins immediately with data.

Example:

1,John,Doe,john@example.com,Male,127.0.0.1
2,Maria,Smith,maria@example.com,Female,127.0.0.2

Command:

WITH (FORMAT CSV)
*/


-- =====================================================================
--                     COLUMN ORDER MUST MATCH
-- =====================================================================

/*
The order inside \copy must match the order of values in the CSV.

CSV order:

id,first_name,last_name,email,gender,ip_address

Correct:

\copy users(id, first_name, last_name, email, gender, ip_address) ...

Wrong:

\copy users(email, first_name, last_name, gender, ip_address, id) ...

PostgreSQL follows the provided order exactly.
*/


-- =====================================================================
--                     IDENTITY SEQUENCE AFTER IMPORT
-- =====================================================================

/*
Important:

When manually importing IDs, the identity sequence may not automatically
move to the highest imported ID.

Example:

CSV imported IDs:

1
2
3
...
1000

The sequence may still think the next ID is 1.

Then a later insert without an ID could cause a duplicate-key error.
*/


-- Synchronize the identity sequence with the highest existing ID.

SELECT setval(
    pg_get_serial_sequence('users', 'id'),
    COALESCE((SELECT MAX(id) FROM users), 1),
    true
);


/*
After synchronization, the next generated ID will be greater than MAX(id).
*/


-- Test automatic ID generation after importing.

INSERT INTO users (
    first_name,
    last_name,
    email,
    gender,
    ip_address
)
VALUES (
    'Generated',
    'User',
    'generated@example.com',
    'Other',
    '127.0.0.1'
)
RETURNING *;


-- =====================================================================
--                        \copy VS COPY
-- =====================================================================

/*
\copy:

- psql client command.
- Reads the file from your local/client computer.
- Usually easier for local files.
- Does not require the PostgreSQL server process to access your file path.

COPY:

- PostgreSQL server-side SQL command.
- Reads the file from the database server's filesystem.
- The PostgreSQL server must have permission to access the file.
- Often requires elevated database privileges.

Local Windows file:

    Use \copy.

File physically stored on the database server:

    COPY may be appropriate.
*/


