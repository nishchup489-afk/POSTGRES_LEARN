-- =====================================================================
--                     IMPORTING CSV DATA WITH \copy
-- =====================================================================

/*
\copy:

- A psql meta-command used to import data from a file into a PostgreSQL table.
- It reads the file from the computer where the psql client is running.
- It is not normal SQL.
- It works inside psql, but usually not inside DataGrip's SQL console.

Basic syntax:

\copy table_name(column1, column2, column3)
FROM 'file_path'
WITH (FORMAT CSV, HEADER);
*/


-- =====================================================================
--                         CREATE THE TABLE
-- =====================================================================

DROP TABLE IF EXISTS users;

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(128),
    last_name VARCHAR(128),
    email VARCHAR(128),
    gender VARCHAR(20),
    ip_address VARCHAR(30)
);


/*
GENERATED BY DEFAULT AS IDENTITY:

- PostgreSQL normally generates the ID automatically.
- However, an explicitly provided ID is also allowed.
- This is useful when importing CSV files that already contain IDs.

Compare:

GENERATED ALWAYS AS IDENTITY
    - PostgreSQL generates the ID.
    - Manual IDs are normally rejected.

GENERATED BY DEFAULT AS IDENTITY
    - PostgreSQL generates the ID when no ID is provided.
    - Manual IDs are allowed.
*/


-- =====================================================================
--                         EXAMPLE CSV FILE
-- =====================================================================

/*
MOCK_DATA.csv might contain:

id,first_name,last_name,email,gender,ip_address
1,Zebadiah,Lockie,zlockie0@cnbc.com,Male,180.112.26.232
2,Maria,Smith,msmith@example.com,Female,192.168.1.20
3,John,Doe,jdoe@example.com,Male,10.0.0.15

The first row is the header.
Every following row contains six values.
*/


-- =====================================================================
--                        IMPORT THE CSV FILE
-- =====================================================================

\copy users(id, first_name, last_name, email, gender, ip_address) FROM 'C:/Users/nishc/Downloads/MOCK_DATA.csv' WITH (FORMAT CSV, HEADER);


/*
Meaning:

\copy
    - psql command that imports data.

users(...)
    - Destination table and the exact column order.

FROM 'C:/Users/nishc/Downloads/MOCK_DATA.csv'
    - Path to the CSV file on the client computer.

FORMAT CSV
    - Tells PostgreSQL to parse the file as CSV.

HEADER
    - Tells PostgreSQL to skip the first row because it contains column names.
*/


-- =====================================================================
--                        VERIFY THE IMPORT
-- =====================================================================

SELECT *
FROM users
LIMIT 10;


-- Count all imported rows.

SELECT COUNT(*)
FROM users;


-- View selected columns.

SELECT
    id,
    first_name,
    last_name,
    email
FROM users
LIMIT 20;


-- =====================================================================
--                         IMPORTANT: ONE LINE
-- =====================================================================

/*
\copy must be entered as one complete psql command.

Correct:

\copy users(id, first_name, last_name, email, gender, ip_address) FROM 'C:/Users/nishc/Downloads/MOCK_DATA.csv' WITH (FORMAT CSV, HEADER);

Wrong:

\copy users(id, first_name, last_name, email, gender, ip_address)

FROM 'C:/Users/nishc/Downloads/MOCK_DATA.csv'
WITH (FORMAT CSV, HEADER);

Why?

\copy is a psql meta-command, not a normal SQL statement.
psql expects the complete meta-command on the same line.
*/


-- =====================================================================
