*/


-- =====================================================================
--                      COMMON ERROR: WRONG TABLE
-- =====================================================================

/*
Error:

relation "track_raw" does not exist

Cause:

The \copy command tried to import into a table named track_raw,
but that table was never created.

Wrong:

\copy track_raw(...)

Correct:

\copy users(...)
*/


-- =====================================================================
--                   COMMON ERROR: EXTRA CSV COLUMN
-- =====================================================================

/*
Error:

extra data after last expected column

Example CSV row:

1,Zebadiah,Lockie,zlockie0@cnbc.com,Male,180.112.26.232

This row contains six values:

1. id
2. first_name
3. last_name
4. email
5. gender
6. ip_address

But this command expects only five:

\copy users(first_name, last_name, email, gender, ip_address) ...

Therefore, PostgreSQL sees one extra value.

Fix:

Include id in the column list:

\copy users(id, first_name, last_name, email, gender, ip_address) ...
*/


